#include<stdio.h>

int main()
{
    // 数组大小设为100010，满足n<1e5的要求
    int a[100010], n, max, min, mid;

    // 读取n（标准scanf兼容所有编译器，且适合大规模输入）
    scanf("%d", &n);

    // 读取n个有序整数
    for (int i = 0; i < n; i++)
        scanf("%d", &a[i]);

    // 步骤1：求最大值和最小值（有序数列首尾比较）
    max = (a[0] > a[n - 1]) ? a[0] : a[n - 1];
    min = (a[0] < a[n - 1]) ? a[0] : a[n - 1];

    // 步骤2：求中位数（有序数列直接取中间位置）
    if (n % 2 == 1)
    {
        // 奇数个元素：中间下标为n/2
        mid = a[n / 2];
    }
    else
    {
        // 偶数个元素：中间两个下标之和的平均值（输入为偶数，和必为偶数，无小数）
        mid = (a[n / 2 - 1] + a[n / 2]) / 2;
    }

    // 步骤3：输出结果（最大值 中位数 最小值）
    printf("%d %d %d\n", max, mid, min);

    return 0;
}