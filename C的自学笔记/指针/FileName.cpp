//内存四区
/*
   在系统为程序开辟内存时，将内存分配为4块
   1.栈区
       存放函数的形参，局部变量
	   由系统自动分配和释放，当块(复合语句，函数体)执行完毕后自动释放
   2.堆区
       用于动态内存申请的区块
	   由用户主动申请和释放
   3.全局数据区(全局静态常量区)
       存放全局数据，静态变量，字符串常量
	   程序结束系统自动释放
   4.代码区
       存放可执行的代码
*/

